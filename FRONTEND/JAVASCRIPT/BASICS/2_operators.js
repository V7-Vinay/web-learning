// ARTHEMETIC OPERATORS
// addition + , subtraction - , multiplication * , division / 
//  modulus % , increment ++ , decrement -- ,  exponential **
let a = 3;
let x = (100 + 50) * a-3;// +,-,*
console.log(x);
x%=4; // x = x % 3
console.log(x);
x**=2; // x = x^2
console.log(x);

